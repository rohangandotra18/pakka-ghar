// Generates what the map needs inside the app (run by `npm run map:engine`, and on npm install):
//   src/shared/map/mapEngine.generated.ts  MAPLIBRE_JS (the library) and MAPCORE_SCRIPT (src/shared/map/mapCore.js as a
//                                          classic script), both used only by the phone's web view;
//   src/shared/map/mapCss.generated.ts     MAPLIBRE_CSS, loaded lazily by the website and used by the web view.
// The two are separate so the website never bundles MapLibre's 900 KB of JS twice: it imports the library lazily and only
// the CSS module from here. Only the map tiles, style and fonts come over the network.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const FACTORY = 'createMapCore';

/* mapCore.js is an ES module with exactly one export. A classic <script> in the web view cannot run `export`, so this
   small text transform makes it a classic script:
     1. the single line starting `export function createMapCore(` loses its `export ` prefix (nothing else changes);
     2. the whole file is wrapped in `(function (g) { "use strict"; ... g.createMapCore = createMapCore; })(window)`, so the
        factory becomes the global `createMapCore` and nothing else leaks;
     3. any `</script` is escaped, since the text is inlined in an HTML <script>.
   It throws if the file is not shaped like that (another export, any import, no or several factories, or output that does
   not parse), so a change to mapCore.js that the web view could not run fails the build instead of the phone. */
function toClassicScript(source) {
  const fail = why => { throw new Error(`mapCore.js: ${why}. build-map-engine.js only supports one \`export function ${FACTORY}(\` and no imports.`); };
  const factoryLine = new RegExp(`^export function ${FACTORY}\\(`, 'gm');
  const found = source.match(factoryLine);
  if (!found || found.length !== 1) fail(`expected exactly one \`export function ${FACTORY}(\` at the start of a line, found ${found ? found.length : 0}`);
  const others = source.split('\n').filter(l => /^\s*(export|import)\b/.test(l) && !new RegExp(`^export function ${FACTORY}\\(`).test(l));
  if (others.length) fail(`unsupported module syntax: ${others[0].trim()}`);
  const body = source.replace(factoryLine, `function ${FACTORY}(`);
  const script = `(function (g) {\n"use strict";\n${body}\ng.${FACTORY} = ${FACTORY};\n})(typeof window !== 'undefined' ? window : globalThis);\n`
    .replace(/<\/script/gi, '<\\/script');
  try { new vm.Script(script, { filename: 'mapCore.classic.js' }); } catch (e) { fail(`the web view copy does not parse (${e.message})`); }
  return script;
}

function build() {
  const root = path.join(__dirname, '..');
  const dist = path.join(root, 'node_modules', 'maplibre-gl', 'dist');
  const dir = path.join(root, 'src', 'shared', 'map');
  const js = fs.readFileSync(path.join(dist, 'maplibre-gl.js'), 'utf8').replace(/<\/script/gi, '<\\/script');
  const css = fs.readFileSync(path.join(dist, 'maplibre-gl.css'), 'utf8').replace(/<\/style/gi, '<\\/style');
  const version = require(path.join(dist, '..', 'package.json')).version;
  const core = toClassicScript(fs.readFileSync(path.join(dir, 'mapCore.js'), 'utf8'));
  const note = `// Generated by scripts/build-map-engine.js (npm run map:engine) from maplibre-gl ${version}. Do not edit.\n`;
  fs.writeFileSync(path.join(dir, 'mapEngine.generated.ts'), note +
    `export const MAPLIBRE_VERSION = ${JSON.stringify(version)};\n` +
    `export const MAPLIBRE_JS = ${JSON.stringify(js)};\n` +
    `export const MAPCORE_SCRIPT = ${JSON.stringify(core)};\n`);
  fs.writeFileSync(path.join(dir, 'mapCss.generated.ts'), note + `export const MAPLIBRE_CSS = ${JSON.stringify(css)};\n`);
  console.log(`map engine: maplibre-gl ${version}, ${Math.round((js.length + css.length) / 1024)} KB + mapCore ${Math.round(core.length / 1024)} KB -> src/shared/map/*.generated.ts`);
}

if (require.main === module) build();
module.exports = { toClassicScript };
