def _rupees(paise: int) -> str:
    return f'Rs {paise / 100:,.0f}'


# ---- making the document -----------------------------------------------------------------------------------

def _text_pages(title: str, blocks: list[tuple[str, str]], footer: str) -> bytes:
    """A plain, readable A4 PDF from headed paragraphs."""
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer
    st = getSampleStyleSheet()
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm, topMargin=20 * mm, bottomMargin=20 * mm,
                            title=title, author='Pakka Ghar')
    flow = [Paragraph(title, st['Title']), Spacer(1, 4 * mm)]
    for head, body in blocks:
        if head:
            flow.append(Paragraph(head, st['Heading3']))
        for para in body.split('\n'):
            flow.append(Paragraph(para, st['BodyText']))
        flow.append(Spacer(1, 2 * mm))
    flow += [Spacer(1, 6 * mm), Paragraph(footer, st['Italic'])]
    doc.build(flow)
    return buf.getvalue()


def _cover(b: Booking) -> list[tuple[str, str]]:
    p, room = b.bed.room.property, b.bed.room
    owner = next(iter(owners_of(b.organisation)), None)
    start = b.stay_period.lower.astimezone(IST).date()
    end = b.stay_period.upper.astimezone(IST).date() if b.stay_period.upper else None
    return [
        ('The parties', f'Owner: {owner.name if owner else p.organisation.name}, for {p.name} ("the PG").\n'
                        f'Resident: {b.guest.name}, mobile ending {b.guest.phone[-4:]}, identity verified through DigiLocker'
                        f'{f" (Aadhaar ending {b.guest.aadhaar_masked[-4:]})" if b.guest.aadhaar_masked else ""}.'),
        ('The accommodation', f'Room {room.number} ({room.get_kind_display()}), bed {b.bed.label}, at {p.address}.'),
        ('Term', f'{b.months} months from {start:%-d %B %Y}{f" to {end:%-d %B %Y}" if end else ""}.'),
        ('Money', f'Rent: {_rupees(b.rent_paise)} a month, due by the 5th, paid only in the Pakka Ghar app.\n'
                  f'Deposit: {_rupees(b.deposit_paise)}, held by the payment partner\'s escrow until move-out.\n'
                  f'Electricity: by the room\'s meter at {p.tariff_paise / 100:.2f} rupees a unit, added to the monthly bill.\n'
                  'No cash: neither party will ask for or accept cash for anything under this agreement.'),
        ('Reference', f'Booking {b.reference}. Generated by Pakka Ghar on {timezone.now().astimezone(IST):%-d %B %Y}.'),
    ]


