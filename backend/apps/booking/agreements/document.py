def build_document(a: Agreement) -> Agreement:
    """The document both sides will read: a filled-in cover page, then the owner's PDF (or the standard terms)."""
    from pypdf import PdfReader, PdfWriter
    b = a.booking
    p = b.bed.room.property
    tpl = AgreementTemplate.objects.filter(property=p, active=True).order_by('-created_at').first()
    cover = _text_pages(f'PG accommodation agreement: {p.name}', _cover(b) if tpl else _cover(b) + STANDARD,
                        'Read every page. Both parties sign electronically in the Pakka Ghar app; a signature certificate '
                        'with this document\'s fingerprint is added to the signed copy.')
    out = PdfWriter()
    for page in PdfReader(io.BytesIO(cover)).pages:
        out.add_page(page)
    if tpl:
        with tpl.file.open('rb') as fh:
            for page in PdfReader(io.BytesIO(fh.read())).pages:
                out.add_page(page)
    buf = io.BytesIO()
    out.write(buf)
    data = buf.getvalue()
    a.document.save(f'{b.reference}.pdf', ContentFile(data), save=False)
    a.document_sha256 = hashlib.sha256(data).hexdigest()
    a.pages = len(out.pages)
    a.source = 'owner' if tpl else 'standard'
    a.save(update_fields=['document', 'document_sha256', 'pages', 'source', 'updated_at'])
    return a


def seal(a: Agreement) -> None:
    """Both have signed: the signed copy is the document plus a certificate page. Its own hash is kept too."""
    from pypdf import PdfReader, PdfWriter
    sigs = list(a.signatures.select_related('party').order_by('signed_at'))
    lines = [(f'{s.role.title()}: {s.typed_name}',
              f'Signed {s.signed_at.astimezone(IST):%-d %B %Y, %H:%M:%S} IST. Phone ending {s.party.phone[-4:]}, '
              f'confirmed by one-time code. Read {s.pages_read} of {a.pages} pages. Network address {s.ip or "unknown"}.')
             for s in sigs]
    cert = _text_pages('Signature certificate', [('Document', f'Booking {a.booking.reference}. SHA-256 of the document both '
                                                              f'parties read: {a.document_sha256}')] + lines,
                       'Issued by Pakka Ghar. Any change to the document changes its SHA-256 and voids this certificate.')
    out = PdfWriter()
    with a.document.open('rb') as fh:
        for page in PdfReader(io.BytesIO(fh.read())).pages:
            out.add_page(page)
    for page in PdfReader(io.BytesIO(cert)).pages:
        out.add_page(page)
    buf = io.BytesIO()
    out.write(buf)
    data = buf.getvalue()
    a.signed_document.save(f'{a.booking.reference}-signed.pdf', ContentFile(data), save=False)
    a.signed_sha256 = hashlib.sha256(data).hexdigest()
    a.save(update_fields=['signed_document', 'signed_sha256', 'updated_at'])


_PDFIUM = threading.Lock()   # PDFium is not thread-safe: one render at a time per process, or the server crashes


def render_page(a: Agreement, n: int, signed: bool = False) -> bytes:
    """One page as a JPEG. Pages are cached by the document's fingerprint, so each renders once; a changed
    document has a new fingerprint and never shows a stale page."""
    import pypdfium2 as pdfium
    f = a.signed_document if signed and a.signed_document else a.document
    sha = (a.signed_sha256 if signed and a.signed_document else a.document_sha256) or 'x'
    cache = Path(settings.PRIVATE_ROOT) / 'page-cache' / f'{sha}-{n}.jpg'
    if cache.exists():
        return cache.read_bytes()
    with f.open('rb') as fh:
        data = fh.read()
    with _PDFIUM:
        pdf = pdfium.PdfDocument(data)
        try:
            if not 1 <= n <= len(pdf):
                raise ApiError(404, 'no_page', 'No such page.')
            img = pdf[n - 1].render(scale=1.6).to_pil().convert('RGB')
        finally:
            pdf.close()
    buf = io.BytesIO()
    img.save(buf, 'JPEG', quality=80)
    out = buf.getvalue()
    cache.parent.mkdir(parents=True, exist_ok=True)
    tmp = cache.with_suffix(f'.{secrets.token_hex(4)}.tmp')
    tmp.write_bytes(out)
    tmp.replace(cache)
    return out
