"""Agreements: the owner's own PDF or the standard one, read page by page in the app and signed electronically.

How a signature works: the signer has opened every page; they type their full name; a one-time code goes to their
registered phone; with the right code, a Signature is recorded with the time, their network address and device,
and the SHA-256 of the exact document they read. Once both sides have signed, a signed copy is made: the document
plus a certificate page listing both signatures and the hash. Nobody can change a signature afterwards.

This is an OTP-confirmed electronic signature. Aadhaar eSign (a licensed eSign service provider, IT Act 2000
Second Schedule) plugs in at `ESIGN_PROVIDER`; VERIFY with counsel which a PG agreement needs before launch.
"""
